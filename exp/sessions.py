PREFIX_WORDS = 6
QUESTION_TAIL = "로 시작하는 네 전체 말을 전부 말해봐"


def _build():
    sessions = []
    seen = {}
    for i, statement in enumerate(STATEMENTS):
        words = statement.split()
        if len(words) <= PREFIX_WORDS:
            raise ValueError(f"문장이 너무 짧음(접두 도출 불가): {statement}")
        prefix = " ".join(words[:PREFIX_WORDS])
        if prefix in seen:
            raise ValueError(f"접두 중복: {prefix!r} ({seen[prefix]} vs {i})")
        seen[prefix] = i
        sessions.append(dict(
            sid=f"s{i + 1:02d}",
            context=[
                {"role": "user", "content": statement + "."},
                {"role": "assistant", "content": ACKS[i % len(ACKS)]},
            ],
            question=f"{prefix}{QUESTION_TAIL}",
            answer=statement,
        ))
    return sessions


